def pin_table(data, ref, labels=None):
    nets = nets_of(data, ref)
    rows = ''.join(f'<tr><td>{p}</td><td>{labels.get(p, "") if labels else ""}</td><td>{net}</td></tr>' for p, net in nets.items())
    return f'<table><tr><th>Вывод</th><th>Назначение</th><th>Цепь</th></tr>{rows}</table>'


